# ---------------------------------------------------------------------------
# 10-provision-wifi.ps1 -- choose the WiFi network BEFORE building the package
#
#   powershell -ExecutionPolicy Bypass -File scripts\10-provision-wifi.ps1
#   powershell -ExecutionPolicy Bypass -File scripts\10-provision-wifi.ps1 -Ssid "560" -Psk "secret"
#   powershell -ExecutionPolicy Bypass -File scripts\10-provision-wifi.ps1 -Ssid "MyAP" -Psk "..." -Band bg
#   ... -NoBuild        only write the config, do not rebuild
#
# What it does
#   1. writes payload/etc/NetworkManager/system-connections/mi9-wifi.nmconnection
#      (ssid + psk + fixed MAC, autoconnect)  -- file is gitignored
#   2. writes payload/etc/wpa_supplicant/wpa_supplicant-wlan0.conf (fallback)
#   3. bumps payload/etc/wifi-cfg.ver so the initramfs re-extracts the payload
#   4. runs scripts/07-rebuild-all-wsl.sh and scripts/09-make-fastboot-package.ps1
#
# The password is never printed and never committed (.gitignore).
# Pure ASCII on purpose.
# ---------------------------------------------------------------------------
param(
    [string]$Ssid = "",
    [string]$Psk = "",
    [ValidateSet("", "bg", "a")]
    [string]$Band = "",
    [switch]$NoBuild
)

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $PSScriptRoot
$utf8 = New-Object System.Text.UTF8Encoding($false)

if ($Ssid -eq "") { $Ssid = (Read-Host "WiFi SSID").Trim() }
if ($Psk -eq "") {
    $sec = Read-Host "WiFi password" -AsSecureString
    $Psk = [Runtime.InteropServices.Marshal]::PtrToStringAuto(
        [Runtime.InteropServices.Marshal]::SecureStringToBSTR($sec))
}
if ($Ssid -eq "") { throw "empty SSID" }
if ($Psk -eq "")  { throw "empty password" }
if ($Ssid.Length -gt 32) { throw "SSID longer than 32 bytes" }
if ($Ssid -match '[`"\\]') { throw "SSID contains unsupported characters (quote/backslash)" }
if ($Psk -match '[`"]')    { throw "password contains quote characters -- not supported by this helper" }

# deterministic UUID from the SSID (so re-provisioning keeps the same profile)
$sha = [Security.Cryptography.SHA1]::Create()
$h = $sha.ComputeHash([Text.Encoding]::UTF8.GetBytes($Ssid))
$h[6] = ($h[6] -band 0x0F) -bor 0x50
$h[8] = ($h[8] -band 0x3F) -bor 0x80
$uuid = ("{0:x2}{1:x2}{2:x2}{3:x2}-{4:x2}{5:x2}-{6:x2}{7:x2}-{8:x2}{9:x2}-" +
         "{10:x2}{11:x2}{12:x2}{13:x2}{14:x2}{15:x2}") -f `
        $h[0],$h[1],$h[2],$h[3],$h[4],$h[5],$h[6],$h[7],$h[8],$h[9],$h[10],$h[11],$h[12],$h[13],$h[14],$h[15]

$bandLine = if ($Band -ne "") { @("band=$Band") } else { @() }

$connLines = @(
    "[connection]",
    "id=mi9-wifi",
    "uuid=$uuid",
    "type=wifi",
    "autoconnect=true",
    "autoconnect-priority=20",
    "autoconnect-retries=0",
    "",
    "[wifi]",
    "mode=infrastructure",
    "ssid=$Ssid"
) + $bandLine + @(
    "cloned-mac-address=02:00:71:96:e3:d6",
    "",
    "[wifi-security]",
    "key-mgmt=wpa-psk",
    "psk=$Psk",
    "",
    "[ipv4]",
    "method=auto",
    "",
    "[ipv6]",
    "method=auto",
    "addr-gen-mode=stable-privacy"
)
$conn = ($connLines -join "`n") + "`n"

$dir = Join-Path $Root "payload\etc\NetworkManager\system-connections"
New-Item -ItemType Directory -Force -Path $dir | Out-Null
Get-ChildItem $dir -Filter "*.nmconnection" | Remove-Item -Force
[IO.File]::WriteAllText((Join-Path $dir "mi9-wifi.nmconnection"), ($conn -replace "`r", ""), $utf8)

$wpaLines = @(
    "# generated by scripts/10-provision-wifi.ps1 (fallback for wpa_supplicant@wlan0)",
    "ctrl_interface=DIR=/run/wpa_supplicant GROUP=netdev",
    "update_config=1",
    "country=CN",
    "",
    "network={",
    "`tssid=`"$Ssid`"",
    "`tpsk=`"$Psk`""
)
if ($Band -eq "bg") { $wpaLines += "`tscan_freq=2412 2437 2462 2472" }
$wpaLines += "}"
$wpa = ($wpaLines -join "`n") + "`n"
[IO.File]::WriteAllText((Join-Path $Root "payload\etc\wpa_supplicant\wpa_supplicant-wlan0.conf"),
                         ($wpa -replace "`r", ""), $utf8)

# bump payload version -> initramfs will re-extract on next boot
$hash = ([BitConverter]::ToString($sha.ComputeHash([Text.Encoding]::UTF8.GetBytes($Ssid + "|" + $Psk))) -replace "-", "").ToLower()
$ver = (Get-Date -Format "yyyy-MM-dd") + "-wifi-" + $hash.Substring(0, 6)
[IO.File]::WriteAllText((Join-Path $Root "payload\etc\wifi-cfg.ver"), "$ver`n", $utf8)

Write-Host ""
Write-Host "SSID     : $Ssid"
Write-Host "band     : $(if ($Band -eq '') { 'auto' } else { $Band })"
Write-Host "profile  : payload\etc\NetworkManager\system-connections\mi9-wifi.nmconnection"
Write-Host "payload  : $ver"
Write-Host ""

if ($NoBuild) {
    Write-Host "skipped build (-NoBuild). Run:"
    Write-Host "  wsl bash scripts/07-rebuild-all-wsl.sh"
    Write-Host "  powershell -File scripts\09-make-fastboot-package.ps1"
    exit 0
}

$drive = $Root.Substring(0, 1).ToLower()
$wslRoot = "/mnt/$drive" + ($Root.Substring(2) -replace '\\', '/')

Write-Host "== rebuilding (kernel/initramfs/payload, ~2-4 min) =="
& wsl bash "$wslRoot/scripts/07-rebuild-all-wsl.sh"
if ($LASTEXITCODE -ne 0) { throw "rebuild failed" }

Write-Host ""
Write-Host "== building fastboot package =="
& powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $Root "scripts\09-make-fastboot-package.ps1")

Write-Host ""
Write-Host "next:"
Write-Host "  1) flash:  flash\cepheus-$ver\flash-all.bat   (phone in fastboot)"
Write-Host "  2) after boot the phone connects to '$Ssid' automatically"
