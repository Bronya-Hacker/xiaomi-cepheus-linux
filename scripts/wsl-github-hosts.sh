#!/bin/bash
# ---------------------------------------------------------------------------
# wsl-github-hosts.sh -- make github.com usable from WSL2 without a proxy
#
# What goes wrong here:
#   1. WSL resolves github.com to 20.205.243.166, which accepts the TCP
#      connect and then transfers nothing (the request just hangs).
#   2. Windows resolves github.com to 127.0.0.1, because SteamTools / Watt
#      Toolkit listens on :443 and does TLS interception with its own CA.
#      That path works, but every tool then needs -k or GIT_SSL_NO_VERIFY,
#      and WSL2 cannot reach the Windows loopback anyway.
#
# Fix: pin github.com and the hosts git actually talks to onto real GitHub
# IPs in /etc/hosts.  Real certificates then verify, no proxy involved.
#
# Not fixable this way:
#   raw.githubusercontent.com -- the TLS ClientHello for that SNI is reset
#   (185.199.10[89].133 and 185.199.1[01][01].133 all fail).  For raw files
#   use: https://gh-proxy.com/https://raw.githubusercontent.com/<path>
#
# Requirement: /etc/wsl.conf must have
#     [network]
#     generateHosts = false
#   otherwise WSL rewrites /etc/hosts on every start and drops the block.
#
# Usage:
#   sudo bash scripts/wsl-github-hosts.sh            # probe + apply
#   sudo bash scripts/wsl-github-hosts.sh --dry-run  # probe only
# ---------------------------------------------------------------------------
set -u

HOSTS=/etc/hosts
MARK_BEGIN=">>> github-direct"
MARK_END="<<< github-direct"
DRY=0
[ "${1:-}" = "--dry-run" ] && DRY=1

if [ "$(id -u)" != "0" ] && [ "$DRY" = "0" ]; then
	echo "need root: sudo bash $0" >&2
	exit 1
fi

# --- probe helpers ---------------------------------------------------------
# probe <host> <ip> <url> -> prints time_total on success, nothing on failure
probe() {
	local t
	t=$(curl -sS -m 6 --resolve "$1:443:$2" -o /dev/null \
		-w '%{time_total}' "$3" 2>/dev/null) || return 1
	[ -n "$t" ] || return 1
	echo "$t"
}

# pick <host> <url> <ip...> -> prints "ip time" of the fastest answer
pick() {
	local host=$1 url=$2 ip t best_ip="" best_t=""
	shift 2
	for ip in "$@"; do
		t=$(probe "$host" "$ip" "$url") || continue
		printf '  %-42s %-16s %ss\n' "$host" "$ip" "$t" >&2
		if [ -z "$best_t" ] || awk "BEGIN{exit !($t < $best_t)}"; then
			best_ip=$ip
			best_t=$t
		fi
	done
	[ -n "$best_ip" ] && echo "$best_ip $best_t"
}

# pick_first <host> <url> <ip...> -> first IP that answers, no latency race
pick_first() {
	local host=$1 url=$2 ip t
	shift 2
	for ip in "$@"; do
		t=$(probe "$host" "$ip" "$url") || continue
		printf '  %-42s %-16s ok %ss\n' "$host" "$ip" "$t" >&2
		echo "$ip $t"
		return 0
	done
	return 1
}

echo "== probing github.com =="
# 20.27.177.113 (Azure HK) answers the fastest but resets the POST that
# git-receive-pack needs, so this one takes the first IP that answers at all
# (US frontends first) instead of racing for the lowest latency.
GH=$(pick_first github.com \
	"https://github.com/Bronya-Hacker/xiaomi-cepheus-linux.git/info/refs?service=git-upload-pack" \
	140.82.113.3 140.82.112.3 20.27.177.113 20.205.243.166)
[ -z "$GH" ] && {
	echo "no reachable github.com IP" >&2
	exit 1
}
GH_IP=${GH%% *}

echo "== probing release-assets.githubusercontent.com =="
RA=$(pick release-assets.githubusercontent.com \
	https://release-assets.githubusercontent.com/ \
	185.199.110.133 185.199.108.133 185.199.109.133 185.199.111.133)
[ -z "$RA" ] && RA="185.199.110.133 0"
RA_IP=${RA%% *}

# uploads.github.com is only used by release uploads, and it has its own IP:
# 20.205.243.161.  Pointing it at the main frontend (20.205.243.166) makes it
# answer 301 -> https://github.com/repos/... and the upload silently does
# nothing (curl -X POST does not follow 301).
UP_IP=20.205.243.161

echo
echo "github.com            -> $GH_IP"
echo "codeload.github.com   -> $GH_IP"
echo "uploads.github.com    -> $UP_IP"
echo "release-assets        -> $RA_IP"
echo "objects.githubusercontent.com -> $RA_IP"

BLOCK="# $MARK_BEGIN  (generated by scripts/wsl-github-hosts.sh, $(date +%F))
$GH_IP github.com
$GH_IP codeload.github.com
$UP_IP uploads.github.com
$RA_IP release-assets.githubusercontent.com
$RA_IP objects.githubusercontent.com
# $MARK_END"

if [ "$DRY" = "1" ]; then
	echo
	echo "--dry-run, not writing.  Would write:"
	echo "$BLOCK"
	exit 0
fi

if ! grep -q 'generateHosts[[:space:]]*=[[:space:]]*false' /etc/wsl.conf 2>/dev/null; then
	echo
	echo "warning: /etc/wsl.conf has no 'generateHosts = false'; WSL will" >&2
	echo "         regenerate /etc/hosts on restart and drop this block." >&2
fi

cp -a "$HOSTS" "$HOSTS.bak.$(date +%Y%m%d-%H%M%S)"
# drop the block and any old hard-coded github.com line
sed -i "/$MARK_BEGIN/,/$MARK_END/d" "$HOSTS"
sed -i '/^[0-9.]\+[[:space:]]\+github\.com$/d' "$HOSTS"
printf '\n%s\n' "$BLOCK" >>"$HOSTS"

echo
echo "== written; verifying =="
grep -n -A7 "$MARK_BEGIN" "$HOSTS"
if git -C "$(dirname "$0")/.." ls-remote https://github.com/Bronya-Hacker/xiaomi-cepheus-linux.git refs/heads/main >/dev/null 2>&1; then
	echo "[ok] git ls-remote works with normal TLS verification"
else
	echo "[!] git ls-remote failed -- check the IPs above"
fi
